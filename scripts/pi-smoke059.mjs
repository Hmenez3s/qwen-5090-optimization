import assert from 'node:assert/strict';
import fs from 'node:fs';
import {ModelRuntime} from '/Users/operator/npm-global/lib/node_modules/@earendil-works/pi-coding-agent/dist/core/model-runtime.js';
import {ModelRegistry} from '/Users/operator/npm-global/lib/node_modules/@earendil-works/pi-coding-agent/dist/core/model-registry.js';
import {InMemoryCredentialStore,InMemoryModelsStore,Type} from '/Users/operator/npm-global/lib/node_modules/@earendil-works/pi-coding-agent/node_modules/@earendil-works/pi-ai/dist/index.js';
const originalFetch=globalThis.fetch;
let requests=0;
globalThis.fetch=(input,init)=>{
 const url=new URL(typeof input==='string'?input:input instanceof URL?input.href:input.url);
 assert.equal(url.origin,'http://127.0.0.1:8002');
 assert.equal(url.pathname,'/v1/chat/completions');requests++;
 return originalFetch(input,{...init,redirect:'error'});
};
const runtime=await ModelRuntime.create({modelsPath:'/Users/operator/.pi/agent/models.json',credentials:new InMemoryCredentialStore(),modelsStore:new InMemoryModelsStore(),allowModelNetwork:false});
assert.equal(runtime.getError(),undefined);
const registry=new ModelRegistry(runtime);
const model=registry.find('gpu-host','qwen3.8-27b-normal');
assert.ok(model);assert.equal(model.contextWindow,131072);
assert.ok(registry.getAvailable().some(m=>m.provider==='gpu-host'&&m.id===model.id));
const context={messages:[{role:'user',content:'Use add_numbers to calculate 17+25. After receiving its result, return final JSON with key sum.',timestamp:Date.now()}],tools:[{name:'add_numbers',description:'Add two integers.',parameters:Type.Object({a:Type.Integer(),b:Type.Integer()},{additionalProperties:false})}]};
const options={reasoning:'low',temperature:0,maxTokens:1024,signal:AbortSignal.timeout(90000)};
const first=await runtime.completeSimple(model,context,options);
assert.notEqual(first.stopReason,'error',first.errorMessage);
const calls=first.content.filter(x=>x.type==='toolCall');assert.equal(calls.length,1);
assert.equal(calls[0].name,'add_numbers');assert.deepEqual(calls[0].arguments,{a:17,b:25});
context.messages.push(first,{role:'toolResult',toolCallId:calls[0].id,toolName:'add_numbers',content:[{type:'text',text:'{"result":42}'}],isError:false,timestamp:Date.now()});
const second=await runtime.completeSimple(model,context,options);
assert.equal(second.stopReason,'stop',second.errorMessage);
const text=second.content.filter(x=>x.type==='text').map(x=>x.text).join('');
assert.equal(JSON.parse(text.match(/\{[^{}]*\}/)?.[0]??'null')?.sum,42);
const thinking=[first,second].flatMap(x=>x.content).filter(x=>x.type==='thinking').map(x=>x.thinking).join('');assert.ok(thinking.length>0);
const result={status:'PASS',provider:model.provider,model:model.id,contextWindow:model.contextWindow,requests,toolRoundtrip:true,thinkingChars:thinking.length,answer:text,first,second};
fs.writeFileSync('/Users/operator/qwen-5090-optimization/evidence/pi-smoke059.json',JSON.stringify(result,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({status:result.status,provider:result.provider,model:result.model,contextWindow:result.contextWindow,requests,toolRoundtrip:true,thinkingChars:result.thinkingChars,answer:text}));
