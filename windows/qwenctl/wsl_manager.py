def _validate_controller_proof(
    controller: Mapping[str, Any], root: Path, expected_pid: int | None = None
) -> dict[str, Any]:
    if not isinstance(controller, Mapping):
        raise _error("BLOCKED", "controller", "prova do controller ausente")
    raw_matches = controller.get("matches")
    if isinstance(raw_matches, Mapping):
        raw_matches = [raw_matches]
    if not isinstance(raw_matches, list):
        raise _error("BLOCKED", "controller", "prova do controller inválida")
    count = controller.get("count")
    if count != 1 or len(raw_matches) != 1:
        raise _error("BLOCKED", "controller", "controller não é exatamente um")
    match = raw_matches[0]
    if not isinstance(match, Mapping):
        raise _error("BLOCKED", "controller", "entrada do controller inválida")
    command = match.get("command_line")
    if not isinstance(command, str):
        command = match.get("CommandLine")
    if not isinstance(command, str):
        raise _error("BLOCKED", "controller", "linha de comando do controller ausente")
    if str(root) + "/exec-manifest.py" not in command or str(root) + "/launch.json" not in command:
        raise _error("BLOCKED", "controller", "controller não contém o root exato")
    if "cmd.exe" not in command.lower() and str(match.get("name", "")).lower() != "cmd.exe":
        raise _error("BLOCKED", "controller", "processo provado não é cmd.exe")
    pid = match.get("pid", match.get("ProcessId"))
    if expected_pid not in (None, 0):
        if not _is_int(pid) or int(pid) != expected_pid:
            raise _error("BLOCKED", "controller", "PID do controller não corresponde ao recibo local")
    return {
        "count": 1,
        "pid": int(pid) if _is_int(pid) else pid,
        "command_line": command,
    }


def stop_service(
    token: Mapping[str, Any],
    controller: Mapping[str, Any],
    *,
    proc_root: Path = Path("/proc"),
    api_reader: Callable[[int], dict[str, Any] | None] | None = None,
    metrics_reader: Callable[[int], str] | None = None,
    kill_fn: Callable[[int, int], None] = os.kill,
    sleep_fn: Callable[[float], None] = time.sleep,
    monotonic_fn: Callable[[], float] = time.monotonic,
    wait_seconds: float = STOP_WAIT_SECONDS,
) -> dict[str, Any]:
    """Revalidate an exact token, send one SIGTERM, and never escalate."""
    if not isinstance(token, Mapping):
        raise _error("BLOCKED", "identity", "stop token ausente")
    raw_root = token.get("root")
    if not isinstance(raw_root, str):
        raise _error("BLOCKED", "identity", "stop root ausente")
    root = Path(raw_root)
    if not is_allowed_root(root):
        raise _error("BLOCKED", "identity", "root não é gerenciado")
    expected_pid = token.get("pid")
    if not _is_int(expected_pid) or int(expected_pid) <= 0:
        raise _error("BLOCKED", "identity", "stop PID inválido")
    if token.get("model") != MODEL_NAME or token.get("port") not in (PORT, str(PORT)):
        raise _error("BLOCKED", "identity", "stop token não corresponde ao serviço")
    controller_pid = token.get("controller_pid")
    if not _is_int(controller_pid) or int(controller_pid) <= 0:
        raise _error("BLOCKED", "controller", "stop requer PID positivo e pinado do controller")
    proof = _validate_controller_proof(controller, root, int(controller_pid))
    manifest = _read_manifest_for_root(root)
    receipt = _root_receipt(root)
    if receipt is None:
        raise _error("BLOCKED", "identity", "recibo de servidor ausente")
    identity = identity_details(receipt, proc_root=proc_root)
    for key in ("pid", "boot_id", "start_ticks"):
        if str(identity[key]) != str(token.get(key)):
            raise _error("BLOCKED", "identity", "identidade mudou antes do stop")
    if not _cmdline_has_model(proc_root, identity["pid"]):
        raise _error("BLOCKED", "identity", "PID atual não contém o modelo esperado")
    info = api_info(PORT, api_reader)
    if info is not None and info.get("served_model_name") != MODEL_NAME:
        raise _error("BLOCKED", "identity", "API mudou de identidade")
    reader = metrics_reader or _default_metrics_reader
    metrics = _metrics_from_text(reader(PORT))
    # This is the sole signal site in the shipped manager.  There is no retry,
    # SIGKILL, cleanup, or deletion branch after it.
    try:
        kill_fn(identity["pid"], signal.SIGTERM)
    except OSError as exc:
        raise _error("ERROR", "signal", "SIGTERM não foi aceito pelo processo") from exc
    started = monotonic_fn()
    while monotonic_fn() - started <= wait_seconds:
        try:
            current = identity_details(receipt, proc_root=proc_root)
        except ManagerError:
            return {
                "status": "STOPPED",
                "root": str(root),
                "pid": identity["pid"],
                "signal": "SIGTERM",
                "controller": proof,
                "metrics": metrics,
            }
        if current["pid"] != identity["pid"] or current["start_ticks"] != identity["start_ticks"]:
            raise _error("BLOCKED", "identity", "PID mudou durante espera de stop")
        sleep_fn(0.25)
    raise _error(
        "ERROR",
        "timeout",
        "processo não terminou após SIGTERM; nenhuma escalada foi tentada",
        {"root": str(root), "pid": identity["pid"], "signal": "SIGTERM"},
    )


def _find_kda_source() -> Path | None:
    # qwenctl itself runs under WSL's system Python, while SGLang is installed
    # in the interpreter pinned by the validated launch manifest. Resolve the
    # source from that interpreter's venv first instead of assuming it is on
    # this helper process's sys.path.
    try:
        launch = _read_json(TEMPLATE_ROOT / "launch.json", "launch.json template")
        argv = launch.get("argv")
        if isinstance(argv, list) and argv and isinstance(argv[0], str):
            interpreter = Path(argv[0])
            if not interpreter.exists():
                return None
            # Keep the lexical venv path. Its python binary is normally a
            # symlink to /usr/bin; resolving it would incorrectly leave the
            # venv before locating site-packages.
            venv = interpreter.parent.parent
            candidates = sorted(
                venv.glob(
                    "lib/python*/site-packages/sglang/kernels/kda_kernels/"
                    "qwen3x_nvfp4_gemm.py"
                )
            )
            regular = [path for path in candidates if path.is_file() and not path.is_symlink()]
            if len(regular) == 1:
                return regular[0]
    except (ManagerError, OSError, ValueError):
        pass
    try:
        spec = importlib.util.find_spec("sglang.kernels.kda_kernels.qwen3x_nvfp4_gemm")
    except (ImportError, ModuleNotFoundError, ValueError):
        return None
    if spec is None or not isinstance(spec.origin, str) or spec.origin in ("built-in", "frozen"):
        return None
    return Path(spec.origin)


def verify_kda_source(source: Path | str | None = None) -> str:
    """Fail closed if the installed KDA source is not the validated bytes."""
    path = Path(source) if source is not None else _find_kda_source()
    if path is None:
        raise _error("BLOCKED", "kda-source", "fonte KDA instalada não foi encontrada")
    try:
        _ensure_regular(path, "fonte KDA instalada")
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
    except (OSError, ManagerError) as exc:
        raise _error("BLOCKED", "kda-source", "não foi possível verificar fonte KDA") from exc
    if digest != KDA_SOURCE_SHA256:
        raise _error("BLOCKED", "kda-source", "hash da fonte KDA divergente", {"sha256": digest})
    return digest


def _default_command_runner(arguments: Sequence[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        list(arguments),
        check=False,
        capture_output=True,
        text=True,
        timeout=15,
    )


def verify_gpu_exclusive(command_runner: Callable[[Sequence[str]], Any] | None = None) -> int:
    runner = command_runner or _default_command_runner
    result = runner(("/usr/lib/wsl/lib/nvidia-smi", "--query-gpu=memory.free", "--format=csv,noheader,nounits"))
    if getattr(result, "returncode", 1) != 0:
        raise _error("BLOCKED", "gpu", "nvidia-smi não retornou com sucesso")
    readings = [line.strip() for line in str(getattr(result, "stdout", "")).splitlines() if line.strip()]
    if len(readings) != 1:
        raise _error("BLOCKED", "gpu", "não foi provada uma GPU exclusiva")
    try:
        free_mib = int(float(readings[0]))
    except ValueError as exc:
        raise _error("BLOCKED", "gpu", "memória livre da GPU inválida") from exc
    if free_mib < 27000:
        raise _error("BLOCKED", "gpu", "GPU não está exclusivamente disponível")
    return free_mib


def verify_power_limit(command_runner: Callable[[Sequence[str]], Any] | None = None) -> float:
    runner = command_runner or _default_command_runner
    result = runner(("/usr/lib/wsl/lib/nvidia-smi", "--query-gpu=power.limit", "--format=csv,noheader,nounits"))
    if getattr(result, "returncode", 1) != 0:
        raise _error("BLOCKED", "power", "nvidia-smi não retornou limite de potência")
    readings = [line.strip() for line in str(getattr(result, "stdout", "")).splitlines() if line.strip()]
    if len(readings) != 1:
        raise _error("BLOCKED", "power", "limite de potência não é único")
    try:
        limit = float(readings[0])
    except ValueError as exc:
        raise _error("BLOCKED", "power", "limite de potência inválido") from exc
    if limit != POWER_LIMIT_W:
        raise _error("BLOCKED", "power", "limite de potência não é 460 W", {"power_limit_W": limit})
    return limit


def _api_profile_checks(info: Mapping[str, Any], config: Mapping[str, int]) -> dict[str, bool]:
    expected = {
        "served_model_name": MODEL_NAME,
        "context_length": config["context-length"],
        "max_total_num_tokens": config["max-total-tokens"],
        "attention_backend": "flashinfer",
        "speculative_algorithm": "DFLASH",
        "speculative_dflash_block_size": 8,
        "speculative_accept_threshold_single": 1.0,
        "speculative_accept_threshold_acc": 1.0,
        "fp4_gemm_runner_backend": "flashinfer_cutlass",
    }
    return {key: info.get(key) == value for key, value in expected.items()}


def _normalize_for_compare(value: Any, root: Path, template: Path) -> Any:
    result = rewrite_root(copy.deepcopy(value), root, template)
    if isinstance(result, dict):
        result.pop("wait_for", None)
        environment = result.get("environment")
        if isinstance(environment, dict):
            for key in ("TMPDIR", "TMP", "TEMP"):
                if key in environment:
                    environment[key] = "<owned-tmp>"
        argv = result.get("argv")
        if isinstance(argv, list):
            for key, flag in CONFIG_FLAGS.items():
                positions = _arg_positions(argv, flag)
                if len(positions) == 1 and positions[0] + 1 < len(argv):
                    argv[positions[0] + 1] = "<allowlisted>"
    return result


def normalized_launch_equal(template: Mapping[str, Any], candidate: Mapping[str, Any], root: Path) -> bool:
    return _normalize_for_compare(template, TEMPLATE_ROOT, TEMPLATE_ROOT) == _normalize_for_compare(candidate, root, TEMPLATE_ROOT)


def _health_aot(root: Path) -> dict[str, Any]:
    manifest = _read_json(root / "prebuilt-aot.json", "prebuilt-aot.json")
    hashes = _validate_aot_manifest(manifest, root, require_hashes=True)
    version_ok = manifest.get("flashinfer_version") == FLASHINFER_VERSION
    architecture_ok = manifest.get("architecture") == FLASHINFER_ARCHITECTURE
    if not version_ok or not architecture_ok:
        raise ManifestError("versão/arquitetura AOT divergente")
    template_manifest = _read_json(TEMPLATE_ROOT / "prebuilt-aot.json", "prebuilt-aot.json template")
    expected_hashes = _validate_aot_manifest(template_manifest, TEMPLATE_ROOT, require_hashes=True)
    if hashes != expected_hashes:
        raise ManifestError("hashes AOT não correspondem ao catálogo validado")
    return {"count": len(hashes), "sha256": hashes, "version": FLASHINFER_VERSION, "architecture": FLASHINFER_ARCHITECTURE}


def health_check(
    root: Path | str,
    config: Mapping[str, Any] | None = None,
    *,
    api_reader: Callable[[int], dict[str, Any] | None] | None = None,
    command_runner: Callable[[Sequence[str]], Any] | None = None,
    proc_root: Path = Path("/proc"),
    kda_source: Path | str | None = None,
) -> tuple[bool, dict[str, Any], str]:
    """Run read-only identity, profile, hook, AOT, source, and power checks."""
    values = validate_config(config)
    root_path = Path(root)
    checks: dict[str, Any] = {}
    failures: list[str] = []
    try:
        if not is_allowed_root(root_path):
            raise ManifestError("root não é gerenciado")
        manifest = _read_manifest_for_root(root_path)
        active_config = _root_config(manifest)
        checks["identity"] = {"root": str(root_path), "model": MODEL_NAME}
        receipt = _root_receipt(root_path)
        if receipt is None:
            raise _error("NOT_RUNNING", "identity", "server-pid.json ausente")
        checks["identity"].update(identity_details(receipt, proc_root=proc_root))
        if not _cmdline_has_model(proc_root, int(checks["identity"]["pid"])):
            raise _error("BLOCKED", "identity", "PID não contém modelo esperado")
        info = api_info(PORT, api_reader)
        if info is None:
            raise _error("UNHEALTHY", "api", "API privada indisponível")
        api_checks = _api_profile_checks(info, active_config)
        checks["api"] = {"info": info, "checks": api_checks}
        if not all(api_checks.values()):
            failures.append("API/profile")
        checks["profile"] = {
            "active": profile_for_config(active_config),
            "configured": profile_for_config(values),
            "pending_restart": active_config != values,
            "config": active_config,
        }
        if not normalized_launch_equal(_read_json(TEMPLATE_ROOT / "launch.json", "launch.json template"), manifest, root_path):
            failures.append("launch-normalization")
        checks["launch"] = {"normalized": "launch-normalization" not in failures, "port": PORT, "model": MODEL_NAME}

        hook = root_path / "sitecustomize.py"
        kda_hook = root_path / "sitecustomize-kda059.py"
        hook_bytes = hook.read_bytes()
        kda_bytes = kda_hook.read_bytes()
        expected_hook = _rewrite_hook_text((TEMPLATE_ROOT / "sitecustomize-kda059.py").read_text(encoding="utf-8"), TEMPLATE_ROOT, root_path).encode("utf-8")
        expected_marker = KDA_MARKER if root_path.name == "pi-serving-059" else f"QWENCTL_{root_path.name.upper()}_KDA2_ENABLED"
        template_reference_ok = root_path == TEMPLATE_ROOT or str(TEMPLATE_ROOT).encode() not in hook_bytes
        hook_ok = hook_bytes == kda_bytes == expected_hook and str(root_path).encode() in hook_bytes and template_reference_ok and expected_marker.encode() in hook_bytes
        for shape in KDA_SHAPES:
            shape_text = "(" + ",".join(str(part) for part in shape) + ")"
            if shape_text.encode() not in hook_bytes.replace(b" ", b""):
                hook_ok = False
        checks["hook"] = {"root_pin": hook_ok, "kda_shapes": [list(shape) for shape in KDA_SHAPES]}
        if not hook_ok:
            failures.append("hook/root-pin")

        checks["aot"] = _health_aot(root_path)
        source_path = Path(kda_source) if kda_source is not None else _find_kda_source()
        source_ok = False
        source_hash = None
        if source_path is not None:
            try:
                _ensure_regular(source_path, "fonte KDA instalada")
                source_hash = hashlib.sha256(source_path.read_bytes()).hexdigest()
                source_ok = source_hash == KDA_SOURCE_SHA256
            except ManagerError:
                source_ok = False
        checks["kda_source"] = {"sha256": source_hash, "expected": KDA_SOURCE_SHA256, "ok": source_ok}
        if not source_ok:
            failures.append("kda-source")

        runner = command_runner or _default_command_runner
        power_result = runner(("/usr/lib/wsl/lib/nvidia-smi", "--query-gpu=power.limit", "--format=csv,noheader,nounits"))
        output = getattr(power_result, "stdout", "")
        if getattr(power_result, "returncode", 1) != 0:
            raise _error("UNHEALTHY", "power", "nvidia-smi não retornou com sucesso")
        readings = [line.strip() for line in str(output).splitlines() if line.strip()]
        power_ok = len(readings) == 1
        power_value: float | None = None
        if power_ok:
            try:
                power_value = float(readings[0])
                power_ok = power_value == POWER_LIMIT_W
            except ValueError:
                power_ok = False
        checks["power"] = {"limit_W": power_value, "expected_W": POWER_LIMIT_W, "ok": power_ok}
        if not power_ok:
            failures.append("power")
    except ManagerError as exc:
        checks["error"] = {"kind": exc.kind, "message": exc.message}
        failures.append(exc.kind)
    except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError) as exc:
        checks["error"] = {"kind": "health", "message": str(exc)}
        failures.append("health")
    ok = not failures
    active_profile = checks.get("profile", {}).get("active", profile_for_config(values))
    return ok, {"checks": checks, "failures": failures}, active_profile


def _dispatch(request: Mapping[str, Any]) -> dict[str, Any]:
    if request.get("schema_version") != SCHEMA_VERSION:
        raise _error("INVALID_REQUEST", "protocol", "schema_version incompatível")
    operation = request.get("operation")
    if operation not in {"probe", "health", "prepare", "await_ready", "stop"}:
        raise _error("INVALID_REQUEST", "protocol", "operação não permitida")
    values = validate_config(request.get("config"))
    profile = profile_for_config(values)
    if operation == "probe":
        code, data, response_profile = probe(values)
        return envelope(code in {"ALREADY_RUNNING", "STOPPED"}, code, response_profile, data)
    if operation == "prepare":
        code, data, response_profile = probe(values)
        if code == "ALREADY_RUNNING":
            return envelope(True, code, response_profile, data)
        verify_kda_source()
        verify_gpu_exclusive()
        verify_power_limit()
        prepared = prepare_fresh_root(TEMPLATE_ROOT, values)
        return envelope(True, "PREPARED", response_profile, prepared)
    if operation == "await_ready":
        raw_root = request.get("root")
        if not isinstance(raw_root, str) or not is_allowed_root(Path(raw_root)):
            raise _error("BLOCKED", "identity", "root de readiness inválido")
        timeout = values["startup-timeout-seconds"]
        root = Path(raw_root)
        started = time.monotonic()
        while time.monotonic() - started <= timeout:
            item = _inspect_root(root)
            if item.get("blocked"):
                raise _error("NOT_READY", "identity", item.get("reason", "identidade inválida"))
            if item.get("active") and item.get("ready"):
                return envelope(True, "READY", profile, {"root": raw_root, "elapsed": time.monotonic() - started, "api": item.get("api")})
            time.sleep(1.0)
        raise _error("NOT_READY", "readiness", f"serviço não ficou pronto em {timeout}s", {"root": raw_root})
    if operation == "health":
        raw_root = request.get("root")
        if raw_root is None:
            code, data, _ = probe(values)
            if code != "ALREADY_RUNNING":
                raise _error("NOT_RUNNING", "identity", "nenhum serviço conhecido está ativo")
            raw_root = data.get("root")
        if not isinstance(raw_root, str):
            raise _error("NOT_RUNNING", "identity", "root ativo ausente")
        ok, data, response_profile = health_check(raw_root, values)
        return envelope(ok, "HEALTHY" if ok else "UNHEALTHY", response_profile, data, None if ok else {"kind": "health", "message": "uma ou mais verificações falharam"})
    # stop
    token = request.get("stop_token")
    controller = request.get("controller")
    if not isinstance(token, Mapping) or not isinstance(controller, Mapping):
        raise _error("BLOCKED", "controller", "stop requer token e prova do controller")
    if not _is_int(token.get("controller_pid")) or int(token["controller_pid"]) <= 0:
        raise _error("BLOCKED", "controller", "controller_pid positivo é obrigatório")
    data = stop_service(token, controller)
    return envelope(True, "STOPPED", profile, data)


def run_protocol(stream_in: Any = None, stream_out: Any = None) -> int:
    source = stream_in if stream_in is not None else sys.stdin
    target = stream_out if stream_out is not None else sys.stdout
    try:
        raw = source.read()
        request = json.loads(raw)
        if not isinstance(request, dict):
            raise _error("INVALID_REQUEST", "protocol", "request deve ser objeto JSON")
        response = _dispatch(request)
    except ManagerError as exc:
        response = _response_for_error(exc)
    except (OSError, ValueError, TypeError, json.JSONDecodeError) as exc:
        response = _response_for_error(_error("INVALID_REQUEST", "protocol", f"JSON/protocolo inválido: {exc}"))
    target.write(json.dumps(response, sort_keys=True, separators=(",", ":")) + "\n")
    target.flush()
    return 0


if __name__ == "__main__":
    raise SystemExit(run_protocol())
