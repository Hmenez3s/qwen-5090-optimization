def prepare_fresh_root(
    template: Path | str = TEMPLATE_ROOT,
    config: Mapping[str, Any] | None = None,
    *,
    base_root: Path | str | None = None,
    name_factory: Callable[[], str] | None = None,
) -> dict[str, Any]:
    """Copy a validated template into one exclusive, never-reused run root."""
    template_path = Path(template)
    values = validate_config(config)
    source_launch, source_aot = _validate_template(template_path, verify_aot_hashes=False)
    base = Path(base_root) if base_root is not None else template_path.parent
    if base != template_path.parent:
        # A test fixture may explicitly provide a base.  Production always uses
        # the template's parent, so it cannot be redirected by JSON input.
        base.mkdir(parents=True, exist_ok=True)
    _ensure_directory(base, "diretório de runs")
    name = name_factory() if name_factory is not None else utc_root_name()
    if not NEW_ROOT_RE.fullmatch(name):
        raise ManifestError("nome de root gerado inválido")
    root = base / name
    if root.exists() or root.is_symlink():
        raise ManifestError(f"root novo já existe: {root}")
    # mkdir is intentionally exclusive.  From this point every failure leaves
    # the partial root as evidence; there is no cleanup or retry path.
    root.mkdir()
    try:
        rewritten = _rewrite_manifest(source_launch, template_path, root, values)
        aot_directory = Path(source_aot["directory"])
        destination_aot_directory = Path(str(aot_directory).replace(str(template_path), str(root), 1))
        if not _path_is_within(_resolved(destination_aot_directory), _resolved(root)):
            raise ManifestError("destino AOT fora do root novo")
        _ensure_directory(aot_directory, "diretório AOT do template")
        hashes = _validate_aot_manifest(source_aot, template_path, require_hashes=True)
        for rel, digest in hashes.items():
            source = aot_directory / _safe_relative(rel)
            destination = destination_aot_directory / _safe_relative(rel)
            _copy_binary_verified(source, destination, digest)
        rewritten_aot = rewrite_root(copy.deepcopy(dict(source_aot)), template_path, root)
        if not isinstance(rewritten_aot, dict):
            raise ManifestError("manifesto AOT reescrito inválido")
        rewritten_aot["directory"] = str(destination_aot_directory)
        rewritten_aot["sha256"] = dict(hashes)
        if rewritten_aot.get("flashinfer_version") != FLASHINFER_VERSION or rewritten_aot.get("architecture") != FLASHINFER_ARCHITECTURE:
            raise ManifestError("versão/arquitetura AOT não corresponde ao perfil")

        for name_to_copy in (
            "exec-manifest.py",
            "wait-ready024.py",
            "sitecustomize-prebuilt032.py",
            "sitecustomize-kda059.py",
        ):
            source = template_path / name_to_copy
            text = source.read_text(encoding="utf-8")
            rewritten_text = _rewrite_hook_text(text, template_path, root) if name_to_copy == "sitecustomize-kda059.py" else text.replace(str(template_path), str(root))
            _copy_regular(source, root / name_to_copy, rewritten_text)
        kda_text = (root / "sitecustomize-kda059.py").read_text(encoding="utf-8")
        if str(template_path) in kda_text or str(root) not in kda_text:
            raise ManifestError("pin de root KDA não foi reescrito")
        _copy_regular(template_path / "sitecustomize.py", root / "sitecustomize.py", kda_text)

        autotune_source = _autotune_files(source_launch, template_path)
        source_cache_raw = source_launch.get("environment", {}).get("SGLANG_CACHE_DIR") if isinstance(source_launch.get("environment"), dict) else None
        if isinstance(source_cache_raw, str):
            source_cache = Path(source_cache_raw)
            destination_cache = Path(str(source_cache).replace(str(template_path), str(root), 1))
            for source in autotune_source:
                relative = source.relative_to(source_cache)
                _copy_binary_verified(
                    source,
                    destination_cache / relative,
                    hashlib.sha256(source.read_bytes()).hexdigest(),
                )

        _write_json_exclusive(root / "prebuilt-aot.json", rewritten_aot)
        _write_json_exclusive(root / "launch.json", rewritten)
        if (root / "server-pid.json").exists():
            raise ManifestError("server-pid.json não pode existir em root novo")
        # Verify the important postconditions from bytes on disk, not the
        # in-memory objects used to write them.
        disk_launch = _read_json(root / "launch.json", "launch.json novo")
        disk_aot = _read_json(root / "prebuilt-aot.json", "prebuilt-aot.json novo")
        _validate_launch_shape(disk_launch, root)
        _validate_aot_manifest(disk_aot, root, require_hashes=True)
        return {
            "status": "PREPARED",
            "root": str(root),
            "launch": str(root / "launch.json"),
            "aot_libraries": AOT_COUNT,
            "autotune_files": len(autotune_source),
            "server_pid_absent": True,
        }
    except ManagerError as exc:
        # Deliberately do not remove the partial root.  The caller receives the
        # exact partial-root receipt and can inspect it; old/template inputs
        # are never touched.
        data = dict(exc.data) if isinstance(exc.data, Mapping) else {}
        data.setdefault("root", str(root))
        data.setdefault("partial", True)
        raise ManagerError(exc.code, exc.kind, exc.message, data) from exc
    except Exception as exc:
        raise ManagerError(
            "ERROR",
            "prepare",
            f"preparação falhou sem limpeza: {exc}",
            {"root": str(root), "partial": True},
        ) from exc


def _default_api_reader(port: int = PORT, endpoint: str = "/server_info") -> dict[str, Any] | None:
    class _NoRedirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, *args: Any, **kwargs: Any) -> Any:
            raise urllib.error.URLError("redirect recusado")

    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), _NoRedirect())
    try:
        with opener.open(f"http://127.0.0.1:{port}{endpoint}", timeout=3) as response:
            value = json.loads(response.read())
        return value if isinstance(value, dict) else None
    except (OSError, ValueError, urllib.error.URLError):
        return None


def api_info(port: int = PORT, api_reader: Callable[[int], dict[str, Any] | None] | None = None) -> dict[str, Any] | None:
    reader = api_reader or (lambda selected_port: _default_api_reader(selected_port, "/server_info"))
    value = reader(port)
    if value is not None:
        return value
    # The validated service has used both endpoint names over time.  A fallback
    # is read-only and still requires the exact model/profile below.
    if api_reader is None:
        return _default_api_reader(port, "/get_server_info")
    return None


def _read_boot_id(proc_root: Path = Path("/proc")) -> str:
    return (proc_root / "sys/kernel/random/boot_id").read_text(encoding="utf-8").strip()


def _proc_stat(proc_root: Path, pid: int) -> list[str]:
    return (proc_root / str(pid) / "stat").read_text(encoding="utf-8").split()


def identity_details(
    receipt: Mapping[str, Any],
    *,
    proc_root: Path = Path("/proc"),
    boot_id: str | None = None,
) -> dict[str, Any]:
    if not _is_int(receipt.get("pid")) or int(receipt["pid"]) <= 0:
        raise _error("BLOCKED", "identity", "recibo sem PID válido")
    pid = int(receipt["pid"])
    expected_boot = receipt.get("boot_id")
    if not isinstance(expected_boot, str) or not expected_boot:
        raise _error("BLOCKED", "identity", "recibo sem boot identity")
    actual_boot = boot_id if boot_id is not None else _read_boot_id(proc_root)
    if actual_boot != expected_boot:
        raise _error("BLOCKED", "identity", "boot identity mudou")
    try:
        fields = _proc_stat(proc_root, pid)
    except (OSError, ValueError) as exc:
        raise _error("BLOCKED", "identity", "PID registrado não está vivo") from exc
    if len(fields) <= 21 or fields[2] == "Z":
        raise _error("BLOCKED", "identity", "PID registrado está morto ou zumbi")
    expected_start = receipt.get("start_ticks")
    if expected_start is None and isinstance(receipt.get("stat"), str):
        parts = receipt["stat"].split()
        if len(parts) > 21:
            expected_start = parts[21]
    if not isinstance(expected_start, (str, int)):
        raise _error("BLOCKED", "identity", "recibo sem start_ticks")
    expected_start_text = str(expected_start)
    if fields[21] != expected_start_text:
        raise _error("BLOCKED", "identity", "PID foi reutilizado")
    return {
        "pid": pid,
        "boot_id": actual_boot,
        "start_ticks": fields[21],
        "state": fields[2],
    }


def validate_identity(
    receipt: Mapping[str, Any],
    *,
    proc_root: Path = Path("/proc"),
    boot_id: str | None = None,
) -> bool:
    try:
        identity_details(receipt, proc_root=proc_root, boot_id=boot_id)
    except ManagerError:
        return False
    return True


def _cmdline(proc_root: Path, pid: int) -> bytes:
    return (proc_root / str(pid) / "cmdline").read_bytes()


def _cmdline_has_model(proc_root: Path, pid: int) -> bool:
    try:
        raw = _cmdline(proc_root, pid)
    except OSError:
        return False
    expected = MODEL_NAME.encode("utf-8")
    return expected in raw.split(b"\0")


def _read_manifest_for_root(root: Path) -> dict[str, Any]:
    launch_path = root / "launch.json"
    if root == PRODUCTION_TEMPLATE_ROOT:
        _ensure_regular(launch_path, "launch.json template")
        actual_launch_hash = hashlib.sha256(launch_path.read_bytes()).hexdigest()
        if actual_launch_hash != TEMPLATE_LAUNCH_SHA256:
            raise ManifestError("hash do launch.json validado divergiu")
    manifest = _read_json(launch_path, "launch.json")
    _validate_launch_shape(manifest, root)
    return manifest


def _root_config(manifest: Mapping[str, Any]) -> dict[str, int]:
    argv = manifest.get("argv")
    if not isinstance(argv, list):
        raise ManifestError("argv ausente")
    return extract_config_from_argv(argv)


def _root_receipt(root: Path) -> dict[str, Any] | None:
    receipt_path = root / "server-pid.json"
    if not receipt_path.exists() and not receipt_path.is_symlink():
        return None
    return _read_json(receipt_path, "server-pid.json")


def _known_roots(base_root: Path | None = None) -> list[Path]:
    base_root = Path(BASE_ROOT if base_root is None else base_root)
    roots: list[Path] = []
    template = base_root / "pi-serving-059"
    if template.exists() or template.is_symlink():
        roots.append(template)
    if not base_root.exists():
        return roots
    _ensure_directory(base_root, "diretório de runs")
    for item in sorted(base_root.iterdir(), key=lambda p: p.name):
        if item.name.startswith("qwenctl-") and item.is_dir() and not item.is_symlink() and NEW_ROOT_RE.fullmatch(item.name):
            roots.append(item)
    return roots


def _port_is_listening(port: int = PORT) -> bool:
    wanted = f":{port:04X}"
    for proc_net in (Path("/proc/net/tcp"), Path("/proc/net/tcp6")):
        try:
            lines = proc_net.read_text(encoding="ascii").splitlines()[1:]
        except OSError:
            continue
        for line in lines:
            fields = line.split()
            if len(fields) >= 4 and fields[1].rsplit(":", 1)[-1].upper() == wanted and fields[3] == "0A":
                return True
    return False


def _unknown_model_process(
    known: Iterable[Path], proc_root: Path = Path("/proc")
) -> bool:
    known_list = list(known)
    known_resolved = {_resolved(root) for root in known_list}
    try:
        entries = list(proc_root.iterdir())
    except OSError:
        return False
    for entry in entries:
        if not entry.name.isdigit():
            continue
        try:
            pid = int(entry.name)
            raw = _cmdline(proc_root, pid)
        except (OSError, ValueError):
            continue
        if MODEL_NAME.encode("utf-8") not in raw:
            continue
        cwd_link = entry / "cwd"
        try:
            cwd = cwd_link.resolve(strict=True)
        except OSError:
            return True
        if cwd not in known_resolved:
            return True
        # A model process under a known directory is still unknown unless its
        # exact PID is the root's boot/start-pinned server receipt.
        matched_receipt = False
        for root in known_list:
            if _resolved(root) != cwd:
                continue
            try:
                receipt = _root_receipt(root)
                if receipt is not None and int(receipt.get("pid", -1)) == pid:
                    identity_details(receipt, proc_root=proc_root)
                    matched_receipt = True
            except (ManagerError, ValueError, TypeError):
                matched_receipt = False
            break
        if not matched_receipt:
            return True
    return False


def _inspect_root(
    root: Path,
    *,
    api_reader: Callable[[int], dict[str, Any] | None] | None = None,
    proc_root: Path = Path("/proc"),
) -> dict[str, Any]:
    result: dict[str, Any] = {"root": str(root), "active": False, "ready": False}
    if root.is_symlink() or not root.is_dir():
        return result
    try:
        manifest = _read_manifest_for_root(root)
    except ManagerError as exc:
        result["blocked"] = True
        result["reason"] = exc.message
        return result
    result["manifest"] = manifest
    try:
        receipt = _root_receipt(root)
    except ManagerError as exc:
        result["blocked"] = True
        result["reason"] = exc.message
        return result
    if receipt is None:
        return result
    result["receipt"] = receipt
    try:
        identity = identity_details(receipt, proc_root=proc_root)
    except ManagerError as exc:
        # A stale receipt is evidence that this root is stopped, not a reason to
        # mutate or delete it.
        result["stale_receipt"] = True
        result["identity_error"] = exc.message
        return result
    result["identity"] = identity
    if not _cmdline_has_model(proc_root, identity["pid"]):
        result["blocked"] = True
        result["reason"] = "PID registrado não contém o modelo esperado"
        return result
    result["active"] = True
    try:
        result["config"] = _root_config(manifest)
    except ManagerError as exc:
        result["blocked"] = True
        result["reason"] = exc.message
        return result
    info = api_info(PORT, api_reader)
    if info is not None:
        result["api"] = info
        if info.get("served_model_name") != MODEL_NAME:
            result["blocked"] = True
            result["reason"] = "API respondeu com modelo inesperado"
            return result
        result["ready"] = info.get("status") == "ready"
    return result


def _stop_token(item: Mapping[str, Any]) -> dict[str, Any]:
    identity = item.get("identity")
    manifest = item.get("manifest")
    if not isinstance(identity, Mapping) or not isinstance(manifest, Mapping):
        raise _error("BLOCKED", "identity", "não há identidade completa para stop")
    return {
        "root": item["root"],
        "pid": identity["pid"],
        "boot_id": identity["boot_id"],
        "start_ticks": identity["start_ticks"],
        "model": MODEL_NAME,
        "port": PORT,
        "config": item.get("config", {}),
    }


def _discover(
    *,
    base_root: Path | None = None,
    proc_root: Path = Path("/proc"),
    api_reader: Callable[[int], dict[str, Any] | None] | None = None,
    port_checker: Callable[[int], bool] | None = None,
    unknown_process_checker: Callable[[Iterable[Path], Path], bool] | None = None,
) -> dict[str, Any]:
    base = Path(BASE_ROOT if base_root is None else base_root)
    roots = _known_roots(base)
    inspected = [_inspect_root(root, api_reader=api_reader, proc_root=proc_root) for root in roots]
    blocked = [item for item in inspected if item.get("blocked")]
    if blocked:
        raise _error(
            "BLOCKED",
            "identity",
            "estado de processo/root não corresponde ao perfil conhecido",
            {"roots": inspected},
        )
    active = [item for item in inspected if item.get("active")]
    if len(active) > 1:
        raise _error("BUSY", "identity", "mais de um root gerenciado está ativo", {"roots": inspected})
    checker = port_checker or _port_is_listening
    unknown_checker = unknown_process_checker or _unknown_model_process
    if not active:
        if checker(PORT) or unknown_checker(roots, proc_root):
            raise _error(
                "BLOCKED",
                "identity",
                "porta/processo ocupado por serviço desconhecido",
                {"roots": inspected},
            )
        return {"status": "STOPPED", "roots": inspected, "active": None}
    item = active[0]
    token = _stop_token(item)
    configured = dict(CONFIG_DEFAULTS)
    return {
        "status": "RUNNING",
        "root": item["root"],
        "ready": bool(item.get("ready")),
        "identity": item["identity"],
        "api": item.get("api"),
        "active_config": item.get("config"),
        "configured_config": configured,
        "pending_restart": item.get("config") != configured,
        "stop_token": token,
        "roots": inspected,
    }


def probe(
    config: Mapping[str, Any] | None = None,
    **kwargs: Any,
) -> tuple[str, dict[str, Any], str]:
    values = validate_config(config)
    discovered = _discover(**kwargs)
    if discovered["status"] == "STOPPED":
        discovered["configured_config"] = values
        discovered["configured_profile"] = profile_for_config(values)
        return "STOPPED", discovered, profile_for_config(values)
    active_config = discovered.get("active_config") or values
    discovered["configured_config"] = values
    discovered["configured_profile"] = profile_for_config(values)
    discovered["active_profile"] = profile_for_config(active_config)
    discovered["pending_restart"] = active_config != values
    return "ALREADY_RUNNING", discovered, profile_for_config(values)


def _metrics_from_text(text: str) -> dict[str, float]:
    names = ("sglang:num_running_reqs", "sglang:num_queue_reqs")
    found: dict[str, list[float]] = {name: [] for name in names}
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        for name in names:
            if stripped == name or stripped.startswith(name + "{"):
                pieces = stripped.rsplit(None, 1)
                if len(pieces) != 2:
                    continue
                try:
                    value = float(pieces[1])
                except ValueError:
                    continue
                found[name].append(value)
    result: dict[str, float] = {}
    for name, values in found.items():
        if len(values) != 1 or not math.isfinite(values[0]) or values[0] != 0.0:
            raise _error("BUSY", "metrics", "métricas de requisições não estão exatamente em zero")
        result[name] = values[0]
    return result


def metrics_are_idle(text: str) -> bool:
    try:
        _metrics_from_text(text)
    except ManagerError:
        return False
    return True


