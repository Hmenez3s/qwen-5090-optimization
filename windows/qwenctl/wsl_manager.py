def _validate_launch_shape(manifest: Mapping[str, Any], root: Path) -> None:
    if not isinstance(manifest.get("cwd"), str) or Path(manifest["cwd"]) != root:
        raise ManifestError("cwd do manifesto não está no root esperado")
    argv = manifest.get("argv")
    if not isinstance(argv, list) or not argv or not all(isinstance(item, str) for item in argv):
        raise ManifestError("argv do manifesto inválido")
    _check_required_fixed_flags(argv)
    extract_config_from_argv(argv)
    if manifest.get("port") not in (PORT, str(PORT)):
        raise ManifestError("porta do manifesto não é 8081")
    environment = manifest.get("environment")
    if not isinstance(environment, dict):
        raise ManifestError("environment do manifesto inválido")
    if environment.get("HF_HUB_OFFLINE") != "1":
        raise ManifestError("HF_HUB_OFFLINE deve permanecer 1")
    if environment.get("PYTHONDONTWRITEBYTECODE") != "1":
        raise ManifestError("PYTHONDONTWRITEBYTECODE deve permanecer 1")
    tmp = environment.get("TMPDIR")
    if not isinstance(tmp, str) or not tmp.startswith("/tmp/qwen-"):
        raise ManifestError("TMPDIR não pertence ao namespace qwen")


def _validate_template(template: Path, *, verify_aot_hashes: bool = True) -> tuple[dict[str, Any], dict[str, Any]]:
    if template.is_symlink():
        raise ManifestError("template não pode ser symlink")
    _ensure_directory(template, "template")
    launch_path = template / "launch.json"
    if template == PRODUCTION_TEMPLATE_ROOT:
        _ensure_regular(launch_path, "launch.json template")
        actual_launch_hash = hashlib.sha256(launch_path.read_bytes()).hexdigest()
        if actual_launch_hash != TEMPLATE_LAUNCH_SHA256:
            raise ManifestError("hash do launch.json validado divergiu")
    launch = _read_json(launch_path, "launch.json")
    _validate_launch_shape(launch, template)
    if "wait_for" in launch:
        # A golden template can contain a stale predecessor receipt; it may be
        # read and normalized, but it is never copied to a new root.
        if not isinstance(launch["wait_for"], dict):
            raise ManifestError("wait_for do template inválido")
    aot = _read_json(template / "prebuilt-aot.json", "prebuilt-aot.json")
    _validate_aot_manifest(aot, template, require_hashes=verify_aot_hashes)
    for name in (
        "exec-manifest.py",
        "wait-ready024.py",
        "sitecustomize-prebuilt032.py",
        "sitecustomize-kda059.py",
    ):
        _ensure_regular(template / name, name)
    _ensure_regular(template / "sitecustomize.py", "sitecustomize.py")
    kda_bytes = (template / "sitecustomize-kda059.py").read_bytes()
    if (template / "sitecustomize.py").read_bytes() != kda_bytes:
        raise ManifestError("sitecustomize.py do template não é o hook KDA validado")
    kda_text = kda_bytes.decode("utf-8")
    if str(template) not in kda_text or KDA_MARKER not in kda_text:
        raise ManifestError("hook KDA do template perdeu root/marker")
    for shape in KDA_SHAPES:
        if ("(" + ",".join(str(part) for part in shape) + ")").encode() not in kda_bytes.replace(b" ", b""):
            raise ManifestError("hook KDA do template perdeu shape validado")
    return launch, aot


def _safe_relative(rel: str) -> Path:
    candidate = Path(rel)
    if candidate.is_absolute() or ".." in candidate.parts or candidate == Path("."):
        raise ManifestError("caminho relativo de AOT inválido")
    return candidate


def _validate_aot_manifest(
    manifest: Mapping[str, Any], root: Path, require_hashes: bool = True
) -> dict[str, str]:
    directory_raw = manifest.get("directory")
    hashes = manifest.get("sha256")
    if not isinstance(directory_raw, str) or not isinstance(hashes, dict):
        raise ManifestError("manifesto AOT inválido")
    if len(hashes) != AOT_COUNT:
        raise ManifestError("manifesto AOT deve conter exatamente nove bibliotecas")
    directory = Path(directory_raw)
    if directory.is_symlink() or not _path_is_within(_resolved(directory), _resolved(root)):
        raise ManifestError("diretório AOT fora do root")
    _ensure_directory(directory, "diretório AOT")
    normalized: dict[str, str] = {}
    for rel, digest in hashes.items():
        if not isinstance(rel, str) or not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise ManifestError("hash AOT inválido")
        relative = _safe_relative(rel)
        if relative.suffix != ".so":
            raise ManifestError("biblioteca AOT deve ser .so")
        source = directory / relative
        _ensure_no_symlink_components(source, directory)
        info = _ensure_regular(source, "biblioteca AOT")
        if require_hashes:
            actual = hashlib.sha256(source.read_bytes()).hexdigest()
            if actual != digest:
                raise ManifestError(f"hash AOT divergente: {rel}")
        normalized[str(relative)] = digest
        if info.st_nlink != 1:
            raise ManifestError("biblioteca AOT com inode compartilhado")
    return normalized


def _copy_regular(source: Path, destination: Path, text: str | None = None) -> None:
    _ensure_regular(source, "arquivo fonte")
    _ensure_no_symlink_components(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists() or destination.is_symlink():
        raise ManifestError(f"destino já existe: {destination}")
    payload = source.read_bytes() if text is None else text.encode("utf-8")
    with destination.open("xb") as handle:
        handle.write(payload)
        handle.flush()
        os.fsync(handle.fileno())
    try:
        os.chmod(destination, stat.S_IMODE(source.stat().st_mode))
    except OSError:
        pass


def _rewrite_hook_text(text: str, template: Path, root: Path) -> str:
    rewritten = text.replace(str(template), str(root))
    if root != template and KDA_MARKER in rewritten:
        rewritten = rewritten.replace(KDA_MARKER, f"QWENCTL_{root.name.upper()}_KDA2_ENABLED")
    return rewritten


def _copy_binary_verified(source: Path, destination: Path, expected: str) -> None:
    _copy_regular(source, destination)
    actual = hashlib.sha256(destination.read_bytes()).hexdigest()
    if actual != expected:
        raise ManifestError(f"hash copiado divergente: {source.name}")
    source_info = source.stat()
    destination_info = destination.stat()
    if (source_info.st_dev, source_info.st_ino) == (destination_info.st_dev, destination_info.st_ino):
        raise ManifestError("cópia AOT compartilha inode com a fonte")
    if destination_info.st_nlink != 1:
        raise ManifestError("cópia AOT tem hardlink")


def _path_values(value: Any) -> Iterable[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, list):
        for item in value:
            yield from _path_values(item)
    elif isinstance(value, dict):
        for item in value.values():
            yield from _path_values(item)


def _create_run_directories(manifest: Mapping[str, Any], root: Path) -> None:
    """Create only directories named by the normalized run-local manifest."""
    root_resolved = _resolved(root)
    candidates: set[Path] = {root / "home", root / "storage", root / "crash", root / "downloads"}
    environment = manifest.get("environment", {})
    if isinstance(environment, dict):
        for key, raw in environment.items():
            if key in {
                "HOME",
                "HF_HOME",
                "XDG_CACHE_HOME",
                "CUDA_CACHE_PATH",
                "CUTE_DSL_CACHE_DIR",
                "CUTE_DSL_DUMP_DIR",
                "SGLANG_CACHE_DIR",
                "TRITON_CACHE_DIR",
                "TORCHINDUCTOR_CACHE_DIR",
                "TORCH_EXTENSIONS_DIR",
                "FLASHINFER_WORKSPACE_BASE",
            } and isinstance(raw, str):
                candidate = Path(raw)
                if _path_is_within(_resolved(candidate), root_resolved):
                    candidates.add(candidate)
    argv = manifest.get("argv", [])
    if isinstance(argv, list):
        for index, item in enumerate(argv[:-1]):
            if item in {"--file-storage-path", "--crash-dump-folder", "--download-dir"}:
                raw = argv[index + 1]
                if isinstance(raw, str):
                    candidate = Path(raw)
                    if _path_is_within(_resolved(candidate), root_resolved):
                        candidates.add(candidate)
    for candidate in sorted(candidates, key=lambda p: len(p.parts)):
        if not _path_is_within(_resolved(candidate), root_resolved):
            raise ManifestError("diretório de execução fora do root")
        _ensure_no_symlink_components(candidate, root)
        candidate.mkdir(parents=True, exist_ok=True)


def _autotune_files(template_launch: Mapping[str, Any], template: Path) -> list[Path]:
    environment = template_launch.get("environment", {})
    if not isinstance(environment, dict):
        return []
    raw = environment.get("SGLANG_CACHE_DIR")
    if not isinstance(raw, str):
        return []
    cache = Path(raw)
    if not _path_is_within(_resolved(cache), _resolved(template)):
        raise ManifestError("SGLANG_CACHE_DIR do template saiu do root")
    if not cache.exists():
        return []
    _ensure_directory(cache, "SGLANG_CACHE_DIR")
    result: list[Path] = []
    for parent, directories, files in os.walk(cache, followlinks=False):
        parent_path = Path(parent)
        for name in directories + files:
            item = parent_path / name
            if item.is_symlink():
                raise ManifestError("symlink em SGLANG_CACHE_DIR")
        for name in files:
            item = parent_path / name
            if item.suffix == ".json" and "flashinfer" in item.relative_to(cache).parts and "autotune" in item.relative_to(cache).parts:
                _ensure_regular(item, "cache autotune")
                result.append(item)
    return sorted(result)


def _rewrite_manifest(
    source: Mapping[str, Any], template: Path, root: Path, config: Mapping[str, Any]
) -> dict[str, Any]:
    values = validate_config(config)
    if not isinstance(source, dict):
        raise ManifestError("manifesto de lançamento inválido")
    result = rewrite_root(copy.deepcopy(dict(source)), template, root)
    if not isinstance(result, dict):
        raise ManifestError("manifesto reescrito inválido")
    result.pop("wait_for", None)
    result["cwd"] = str(root)
    argv = result.get("argv")
    if not isinstance(argv, list):
        raise ManifestError("argv ausente após reescrita")
    result["argv"] = rewrite_allowlisted_argv(argv, values)
    _validate_launch_shape(result, root)
    environment = result.get("environment")
    if not isinstance(environment, dict):
        raise ManifestError("environment ausente após reescrita")
    # The executor's owned-TMP contract is intentionally strengthened with a
    # per-root namespace.  No user value can select another namespace.
    tmp = f"/tmp/qwen-{root.name}/tmp"
    if "TMPDIR" not in environment:
        raise ManifestError("TMPDIR ausente")
    environment["TMPDIR"] = tmp
    for key in ("TMP", "TEMP"):
        if key in environment:
            environment[key] = tmp
    # These values are path pins, not configuration knobs.  A missing value is
    # left alone, while a present value must remain within the new root after
    # template-root replacement.
    root_resolved = _resolved(root)
    for key in (
        "HOME",
        "HF_HOME",
        "XDG_CACHE_HOME",
        "CUDA_CACHE_PATH",
        "CUTE_DSL_CACHE_DIR",
        "CUTE_DSL_DUMP_DIR",
        "SGLANG_CACHE_DIR",
        "TRITON_CACHE_DIR",
        "TORCHINDUCTOR_CACHE_DIR",
        "TORCH_EXTENSIONS_DIR",
        "FLASHINFER_WORKSPACE_BASE",
    ):
        raw = environment.get(key)
        if isinstance(raw, str) and not _path_is_within(_resolved(Path(raw)), root_resolved):
            raise ManifestError(f"{key} ficou fora do root")
    _create_run_directories(result, root)
    return result


def _write_json_exclusive(path: Path, value: Mapping[str, Any]) -> None:
    _ensure_no_symlink_components(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() or path.is_symlink():
        raise ManifestError(f"arquivo já existe: {path}")
    encoded = (json.dumps(value, indent=2, sort_keys=True) + "\n").encode("utf-8")
    with path.open("xb") as handle:
        handle.write(encoded)
        handle.flush()
        os.fsync(handle.fileno())


