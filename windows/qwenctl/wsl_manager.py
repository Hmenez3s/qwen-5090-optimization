class ManagerError(Exception):
    """A refusal or bounded operation failure with a stable public code."""

    def __init__(self, code: str, kind: str, message: str, data: Any | None = None):
        super().__init__(message)
        self.code = code
        self.kind = kind
        self.message = message
        self.data = data if data is not None else {}


class ManifestError(ManagerError):
    def __init__(self, message: str):
        super().__init__("BLOCKED", "manifest", message)


def _error(code: str, kind: str, message: str, data: Any | None = None) -> ManagerError:
    return ManagerError(code, kind, message, data)


def envelope(
    ok: bool,
    code: str,
    profile: str = "VALIDATED",
    data: Any | None = None,
    error: Mapping[str, str] | None = None,
) -> dict[str, Any]:
    """Create the one stable response shape used by every operation."""
    return {
        "schema_version": SCHEMA_VERSION,
        "ok": bool(ok),
        "code": code,
        "profile": profile,
        "data": {} if data is None else data,
        "error": None if error is None else dict(error),
    }


def _response_for_error(exc: ManagerError, profile: str = "VALIDATED") -> dict[str, Any]:
    return envelope(
        False,
        exc.code,
        profile,
        exc.data,
        {"kind": exc.kind, "message": exc.message},
    )


def _is_int(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def validate_config(raw: Mapping[str, Any] | None) -> dict[str, int]:
    """Validate the four-key desired configuration and return a fresh dict."""
    if raw is None:
        return dict(CONFIG_DEFAULTS)
    if not isinstance(raw, Mapping):
        raise _error("INVALID_CONFIG", "config", "configuração deve ser um objeto JSON")
    unknown = sorted(set(raw) - set(CONFIG_KEYS))
    if unknown:
        raise _error("INVALID_CONFIG", "config", "chave de configuração não permitida")
    values: dict[str, int] = dict(CONFIG_DEFAULTS)
    for key in CONFIG_KEYS:
        if key in raw:
            value = raw[key]
            if not _is_int(value):
                raise _error("INVALID_CONFIG", "config", f"{key} deve ser inteiro")
            values[key] = int(value)
    if not 131072 <= values["context-length"] <= 131200:
        raise _error("INVALID_CONFIG", "config", "context-length deve estar entre 131072 e 131200")
    if not values["context-length"] <= values["max-total-tokens"] <= 131328:
        raise _error(
            "INVALID_CONFIG",
            "config",
            "max-total-tokens deve ser >= context-length e <= 131328",
        )
    if not 0 <= values["random-seed"] <= 2147483647:
        raise _error("INVALID_CONFIG", "config", "random-seed deve estar entre 0 e 2147483647")
    if not 60 <= values["startup-timeout-seconds"] <= 1800:
        raise _error(
            "INVALID_CONFIG",
            "config",
            "startup-timeout-seconds deve estar entre 60 e 1800",
        )
    return values


def profile_for_config(config: Mapping[str, Any]) -> str:
    values = validate_config(config)
    return "VALIDATED" if values == CONFIG_DEFAULTS else "CUSTOM_UNVALIDATED"


def _path_is_within(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
        return True
    except ValueError:
        return False


def _resolved(path: Path) -> Path:
    return path.resolve(strict=False)


def is_allowed_root(root: Path | str, base_root: Path | None = None) -> bool:
    """Return whether a path is exactly the immutable root or a managed root."""
    candidate = Path(root)
    base = Path(BASE_ROOT if base_root is None else base_root)
    if not candidate.is_absolute() or candidate.is_symlink() or ".." in candidate.parts:
        return False
    try:
        candidate_resolved = _resolved(candidate)
        base_resolved = _resolved(base)
    except OSError:
        return False
    if candidate_resolved == base_resolved / "pi-serving-059":
        return True
    if candidate_resolved.parent != base_resolved:
        return False
    return bool(NEW_ROOT_RE.fullmatch(candidate_resolved.name))


def is_managed_root(root: Path | str, base_root: Path | None = None) -> bool:
    return is_allowed_root(root, base_root)


def _ensure_regular(path: Path, description: str) -> os.stat_result:
    if path.is_symlink():
        raise ManifestError(f"{description} não pode ser symlink")
    try:
        info = path.stat()
    except OSError as exc:
        raise ManifestError(f"{description} ausente: {path}") from exc
    if not stat.S_ISREG(info.st_mode):
        raise ManifestError(f"{description} não é arquivo regular: {path}")
    return info


def _ensure_directory(path: Path, description: str) -> None:
    if path.is_symlink():
        raise ManifestError(f"{description} não pode ser symlink")
    try:
        info = path.stat()
    except OSError as exc:
        raise ManifestError(f"{description} ausente: {path}") from exc
    if not stat.S_ISDIR(info.st_mode):
        raise ManifestError(f"{description} não é diretório: {path}")


def _ensure_no_symlink_components(path: Path, stop: Path | None = None) -> None:
    current = path.absolute()
    stop_path = stop.absolute() if stop is not None else None
    stop_resolved = stop_path.resolve(strict=False) if stop_path is not None else None
    original = current
    while True:
        if stop_path is not None and (current == stop_path or current.resolve(strict=False) == stop_resolved):
            return
        if current.exists() or current.is_symlink():
            # When no owned root was supplied, reject the destination itself
            # but do not mistake a platform-level /var -> /private/var alias
            # for a run-local symlink.  Callers validating a source tree pass
            # its owned root as stop and get component-by-component checking.
            if current.is_symlink() and (stop_path is not None or current == original):
                raise ManifestError(f"caminho symlink recusado: {current}")
        if current.parent == current:
            return
        current = current.parent


def _read_json(path: Path, description: str) -> dict[str, Any]:
    _ensure_regular(path, description)
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ManifestError(f"JSON inválido em {description}") from exc
    if not isinstance(value, dict):
        raise ManifestError(f"{description} deve ser objeto JSON")
    return value


def _arg_positions(argv: Sequence[Any], flag: str) -> list[int]:
    return [index for index, value in enumerate(argv) if value == flag]


def _arg_value(argv: Sequence[Any], flag: str) -> str:
    positions = _arg_positions(argv, flag)
    if len(positions) != 1:
        raise ManifestError(f"manifesto deve conter exatamente um {flag}")
    index = positions[0]
    if index + 1 >= len(argv) or not isinstance(argv[index + 1], str) or argv[index + 1].startswith("--"):
        raise ManifestError(f"valor ausente para {flag}")
    return argv[index + 1]


def _require_arg(argv: Sequence[Any], flag: str, expected: str | None = None) -> str:
    value = _arg_value(argv, flag)
    if expected is not None and value != expected:
        raise ManifestError(f"{flag} não corresponde ao perfil validado")
    return value


def extract_config_from_argv(argv: Sequence[Any]) -> dict[str, int]:
    values: dict[str, int] = dict(CONFIG_DEFAULTS)
    for key, flag in CONFIG_FLAGS.items():
        value = _arg_value(argv, flag)
        try:
            parsed = int(value, 10)
        except ValueError as exc:
            raise ManifestError(f"{flag} não é inteiro") from exc
        values[key] = parsed
    return validate_config(values)


def rewrite_allowlisted_argv(argv: Sequence[Any], config: Mapping[str, Any]) -> list[str]:
    values = validate_config(config)
    if not isinstance(argv, Sequence) or isinstance(argv, (str, bytes)):
        raise ManifestError("argv inválido")
    result = list(argv)
    for key, flag in CONFIG_FLAGS.items():
        positions = _arg_positions(result, flag)
        if len(positions) != 1:
            raise ManifestError(f"manifesto deve conter exatamente um {flag}")
        index = positions[0]
        if index + 1 >= len(result) or not isinstance(result[index + 1], str):
            raise ManifestError(f"valor ausente para {flag}")
        result[index + 1] = str(values[key])
    return result


def recursive_replace(value: Any, old: str, new: str) -> Any:
    """Replace only a known template-root string in a JSON-like value."""
    if isinstance(value, str):
        return value.replace(old, new)
    if isinstance(value, list):
        return [recursive_replace(item, old, new) for item in value]
    if isinstance(value, dict):
        return {
            recursive_replace(key, old, new): recursive_replace(item, old, new)
            for key, item in value.items()
        }
    return value


def rewrite_root(value: Any, old_root: Path | str, new_root: Path | str) -> Any:
    return recursive_replace(value, str(old_root), str(new_root))


